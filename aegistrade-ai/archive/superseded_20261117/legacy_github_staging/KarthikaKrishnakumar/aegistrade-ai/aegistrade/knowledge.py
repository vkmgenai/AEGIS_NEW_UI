def tokenize(text: str) -> list[str]:
    return re.findall(r'[a-z0-9]+', str(text).lower())

class SimpleBM25:
    def __init__(self, docs: list[list[str]], k1=1.5, b=0.75):
        self.docs = docs
        self.n = len(docs)
        self.avgdl = sum(len(d) for d in docs) / max(1, len(docs))
        self.k1, self.b = k1, b
        self.df = {}
        for doc in docs:
            for word in set(doc):
                self.df[word] = self.df.get(word,0)+1
    def get_scores(self, query: list[str]) -> np.ndarray:
        out = np.zeros(self.n)
        for word in set(query):
            df = self.df.get(word, 0)
            idf = math.log((self.n - df + 0.5)/(df + 0.5) + 1)
            for i, doc in enumerate(self.docs):
                count=doc.count(word)
                if count:
                    den=count+self.k1*(1-self.b+self.b*len(doc)/max(self.avgdl,1))
                    out[i] += idf*count*(self.k1+1)/den
        return out

def rewrite_query(q: str) -> str:
    """Query-side rewrite: controlled expansion; original text is retained."""
    aliases={
        'stoploss': 'stop loss position risk exit',
        'stop-loss': 'stop loss position risk exit',
        'fresh': 'quote data freshness stale timestamp',
        'duplicate': 'timeout retry order id reconcile idempotent',
        'sell short': 'long only short sell leverage',
        'change order': 'edit approval hash exact payload invalid',
        'max size': 'quantity position cap capital available cash',
        'trade now': 'human approval execution quote stale risk',
    }
    output = str(q).lower()
    for src,dst in aliases.items():
        if src in output:
            output += ' ' + dst
    return output

class PolicyRetriever:
    def __init__(self, docs=None, mode: str='offline'):
        from .corpus import load_corpus,validate_passages,corpus_digest
        self.docs=load_corpus() if docs is None else validate_passages(docs)
        self.corpus_sha256=corpus_digest(self.docs)
        self.texts=[f"{d['title']} {d['text']}" for d in self.docs]
        self.bm25=SimpleBM25([tokenize(t) for t in self.texts])
        self.vect=TfidfVectorizer(ngram_range=(1,2),stop_words='english')
        self.matrix=self.vect.fit_transform(self.texts)
        self.mode=mode
        self.embedder=None
        self.cross_encoder=None
        self.neural_vectors=None
        self.vector_store=None
        if mode == 'neural':
            try:
                from .neural_models import load_models,model_cache,EMBEDDING_MODEL
                self.embedder,self.cross_encoder=load_models(model_cache())
                revision=getattr(self.embedder,'_aegis_revision','unknown')
                embedding_identity=EMBEDDING_MODEL+'@'+revision
                cache=Path(os.getenv('AEGIS_DATA_DIR','data'))/'rag'/'embedding_cache'
                cache.mkdir(parents=True,exist_ok=True)
                import hashlib
                key=hashlib.sha256((self.corpus_sha256+embedding_identity).encode()).hexdigest()
                path=cache/(key+'.npz')
                if path.exists():
                    self.neural_vectors=np.load(path,allow_pickle=False)['vectors']
                else:
                    self.neural_vectors=self.embedder.encode(self.texts,normalize_embeddings=True,show_progress_bar=False)
                    temporary=path.with_suffix('.tmp.npz');np.savez_compressed(temporary,vectors=self.neural_vectors);temporary.replace(path)
                if len(self.neural_vectors)!=len(self.docs):raise ValueError('Embedding cache length mismatch')
                if os.getenv('AEGIS_QDRANT_URL'):
                    from .vector_store import QdrantIndex
                    self.vector_store=QdrantIndex(os.environ['AEGIS_QDRANT_URL'],self.docs,self.neural_vectors)
                else:
                    from .vector_store import ChromaIndex
                    folder=os.getenv('AEGIS_CHROMA_PATH',str(Path(os.getenv('AEGIS_DATA_DIR','data'))/'rag'/'chroma'))
                    self.vector_store=ChromaIndex(folder,self.docs,self.neural_vectors,embedding_identity)
            except Exception as exc:
                raise RuntimeError('Neural RAG unavailable: inspect local models, embedding cache and vector-store setup. No offline fallback was used.') from exc
        elif mode != 'offline':
            raise ValueError('mode must be offline or neural')
    def search(self, query: str, top_k=4, rewrite=True, as_of=None,required_ids=None):
        if not isinstance(top_k,int) or not 1<=top_k<=20:raise ValueError('top_k must be 1..20')
        allowed=list(range(len(self.docs)))
        if as_of:
            from datetime import date
            cutoff=date.fromisoformat(str(as_of))
            allowed=[i for i,d in enumerate(self.docs) if d.get('authority')!='external_reference' or
                     date.fromisoformat(d.get('published_date') or d.get('retrieved_date') or d['date'])<=cutoff]
        if not allowed:return []
        # Citation verification is exact lookup, independent of semantic reranking.
        requested=list(dict.fromkeys(list(required_ids or [])+re.findall(r'\b(?:POL-\d{2,}|REF-[A-Z0-9-]+)\b',query)))
        pinned=[i for passage_id in requested for i in allowed if self.docs[i]['id']==passage_id]
        if len(pinned)>top_k:raise ValueError('Requested policy IDs exceed top_k')
        q=rewrite_query(query) if rewrite else query
        bm=self.bm25.get_scores(tokenize(q))
        if self.neural_vectors is None:
            dense=(self.matrix @ self.vect.transform([q]).T).toarray().ravel()
        else:
            embedding=self.embedder.encode([q],normalize_embeddings=True,show_progress_bar=False)[0]
            dense=self.vector_store.scores(embedding) if self.vector_store else self.neural_vectors @ embedding
        if self.neural_vectors is None and max(float(bm.max()),float(dense.max()))<=0:
            return [dict(self.docs[i],retrieval_mode='exact_id',corpus_sha256=self.corpus_sha256) for i in pinned]
        rrf=np.zeros(len(self.docs))
        for scores in (bm,dense):
            order=sorted(allowed,key=lambda i:(-scores[i],self.docs[i]['id']))
            for rank,idx in enumerate(order,1):
                rrf[idx] += 1/(60+rank)
        candidates=sorted(allowed,key=lambda i:(-rrf[i],self.docs[i]['id']))[:min(12,len(allowed))]
        if self.cross_encoder is None:
            qterms=set(tokenize(q))
            rerank={int(i):float(rrf[i]+0.015*len(qterms.intersection(tokenize(self.texts[i])))/max(len(qterms),1)) for i in candidates}
        else:
            ce=self.cross_encoder.predict([[q,self.texts[int(i)]] for i in candidates])
            rerank={int(i):float(ce[j]) for j,i in enumerate(candidates)}
        ranking=(pinned+[i for i in sorted(candidates,key=lambda i:rerank[int(i)],reverse=True) if i not in pinned])[:top_k]
        return [dict(self.docs[int(i)],retrieval_score=round(rerank[int(i)],5) if i in rerank else None,
            retrieval_mode='exact_id' if i in pinned else self.mode,corpus_sha256=self.corpus_sha256) for i in ranking]

def evaluate_retrieval(retriever: PolicyRetriever, labelled_queries: list[dict], top_k=5, rewrite=True) -> dict:
    rows=[]
    for case in labelled_queries:
        returned=[p['id'] for p in retriever.search(case['query'],top_k=top_k,rewrite=rewrite)]
        relevant=set(case['relevant_ids'])
        if not relevant:raise ValueError('Every labelled query needs at least one relevant passage')
        matched=len(relevant.intersection(returned))
        rows.append({'id':case['id'],'hit':matched>0,'recall':matched/len(relevant),
                     'returned':returned,'relevant':sorted(relevant)})
    count=len(rows)
    hit=sum(r['hit'] for r in rows)/max(1,count)
    recall=sum(r['recall'] for r in rows)/max(1,count)
    return {'queries':count,'recall_at_k':round(recall,4),'hit_at_k':round(hit,4),'k':top_k,
            'recall_at_5_proxy':round(hit,4),'rows':rows,
            'metric_note':'Macro passage Recall@k; hit@k is reported separately. Labels still require independent relevance review.'}


def get_retriever(mode=None):
    from .corpus import corpus_info
    chosen=mode or os.getenv('AEGIS_RETRIEVAL_MODE','offline')
    return _cached_retriever(chosen,corpus_info()['sha256'],os.getenv('AEGIS_DATA_DIR','data'),
        os.getenv('AEGIS_CHROMA_PATH',''),os.getenv('AEGIS_QDRANT_URL',''))

from functools import lru_cache
@lru_cache(maxsize=4)
def _cached_retriever(mode,digest,data_dir,chroma_path,qdrant_url):
    return PolicyRetriever(mode=mode)
